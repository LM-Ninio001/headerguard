"""Render a Report as terminal text, JSON or a self-contained HTML page."""

from __future__ import annotations

import json
from html import escape

from headerguard.headers import FAIL, PASS, WARN
from headerguard.scanner import Report

LABELS = {PASS: "PASS", WARN: "WARN", FAIL: "FAIL"}
GRADE_COLOURS = {"A": "#1a7f37", "B": "#4c9a2a", "C": "#b58900", "D": "#d9730d", "E": "#cf4b13", "F": "#cf222e"}


def to_text(report: Report, colour: bool = False) -> str:
    codes = {PASS: "\033[32m", WARN: "\033[33m", FAIL: "\033[31m"} if colour else {}
    reset = "\033[0m" if colour else ""
    g = report.grade
    lines = [
        f"Scanned {report.final_url} (HTTP {report.status})",
        f"Grade: {g.letter}   Score: {g.score}/100   "
        f"({g.passed} passed, {g.warnings} warnings, {g.failed} failed)",
        "",
    ]
    for f in report.findings:
        tag = f"{codes.get(f.status, '')}[{LABELS[f.status]}]{reset}"
        lines.append(f"{tag} {f.header:<27} {f.message}")
        if f.status != PASS:
            lines.append(f"       fix: {f.fix}")
    return "\n".join(lines)


def to_json(report: Report) -> str:
    return json.dumps(report.to_dict(), indent=2)


def to_html(report: Report) -> str:
    """A single HTML file with inline CSS, safe to email or open offline."""
    g = report.grade
    colour = GRADE_COLOURS.get(g.letter, "#57606a")
    rows = []
    for f in report.findings:
        fix = "" if f.status == PASS else f"<p class='fix'><b>Fix:</b> <code>{escape(f.fix)}</code></p>"
        risk = "" if f.status == PASS else f"<p class='risk'>{escape(f.risk)}</p>"
        rows.append(
            f"<li class='{f.status}'><span class='tag'>{LABELS[f.status]}</span>"
            f"<div><h3>{escape(f.header)}</h3><p>{escape(f.message)}</p>{risk}{fix}</div></li>"
        )
    return f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>HeaderGuard report: {escape(report.final_url)}</title>
<style>
  body {{ font-family: system-ui, sans-serif; max-width: 860px; margin: 2rem auto; padding: 0 1rem; color: #1f2328; background: #fff; }}
  header {{ display: flex; gap: 1.5rem; align-items: center; border-bottom: 1px solid #d0d7de; padding-bottom: 1.5rem; }}
  .badge {{ width: 96px; height: 96px; border-radius: 50%; background: {colour}; color: #fff;
           display: grid; place-items: center; font-size: 3rem; font-weight: 700; flex: none; }}
  h1 {{ font-size: 1.3rem; margin: 0 0 .3rem; word-break: break-all; }}
  .meta {{ color: #57606a; margin: 0; }}
  ul {{ list-style: none; padding: 0; }}
  li {{ display: flex; gap: 1rem; padding: 1rem 0; border-bottom: 1px solid #eaeef2; }}
  li h3 {{ margin: 0 0 .25rem; font-size: 1rem; }}
  li p {{ margin: .25rem 0; }}
  .tag {{ flex: none; width: 3.5rem; text-align: center; font-size: .75rem; font-weight: 700;
         border-radius: 4px; padding: .2rem 0; height: fit-content; color: #fff; }}
  .pass .tag {{ background: #1a7f37; }} .warn .tag {{ background: #9a6700; }} .fail .tag {{ background: #cf222e; }}
  .risk {{ color: #57606a; }}
  code {{ background: #f6f8fa; padding: .1rem .3rem; border-radius: 4px; word-break: break-all; }}
  footer {{ color: #57606a; font-size: .85rem; margin-top: 2rem; }}
</style>
</head>
<body>
<header>
  <div class="badge" aria-label="Grade {g.letter}">{g.letter}</div>
  <div>
    <h1>{escape(report.final_url)}</h1>
    <p class="meta">Score {g.score}/100 &middot; {g.passed} passed, {g.warnings} warnings, {g.failed} failed</p>
    <p class="meta">Scanned {escape(report.scanned_at)} (HTTP {report.status})</p>
  </div>
</header>
<ul>
{chr(10).join(rows)}
</ul>
<footer>Generated by HeaderGuard v{escape(report.version)}. Passive scan: only a normal page request and TLS handshake were made.</footer>
</body>
</html>
"""
